    #[test]
    fn failure_at_each_filesystem_boundary_is_restart_recoverable() {
        let _process_gate = PROCESS_PROBE_GATE.lock().unwrap();
        let groups_path = PathBuf::from("webinfo/special_upstream_groups.json");
        let dump_path = PathBuf::from("cache/cache_all.dump");
        let old_dump = crate::cache_dump::encode(&[mosdns_cache_core::NativeSnapshotEntry {
            attachment: None,
            key: b"old-cache-key".to_vec(),
            response: b"old-cache-response".to_vec(),
            times: [1; 3],
            wall_times: Some([1, 1, 1]),
            domain_set: Vec::new(),
        }])
        .unwrap();
        let new_dump = crate::cache_dump::encode(&[]).unwrap();
        let allowed_cache_dumps = std::collections::BTreeSet::from([dump_path.clone()]);
        let mut injected = 0;
        for boundary in 1..100 {
            let root = std::env::temp_dir().join(format!(
                "native-journal-fault-{}-{boundary}",
                std::process::id()
            ));
            let _ = std::fs::remove_dir_all(&root);
            std::fs::create_dir_all(root.join("webinfo")).unwrap();
            std::fs::create_dir_all(root.join("cache")).unwrap();
            std::fs::write(root.join(&groups_path), b"old").unwrap();
            std::fs::write(root.join(&dump_path), &old_dump).unwrap();
            let mut owner = ManagedStore::open(&root).unwrap();
            IO_FAIL_AFTER.with(|fault| fault.set(Some(boundary)));
            let mut committed = false;
            let result = (|| {
                owner.prepare_with_inputs(
                    0,
                    1,
                    vec![
                        (groups_path.clone(), Some(b"new".to_vec())),
                        (dump_path.clone(), Some(new_dump.clone())),
                    ],
                    Vec::new(),
                    &allowed_cache_dumps,
                )?;
                owner.replace_prepared()?;
                owner.mark_committed()?;
                committed = true;
                owner.finish_retirement()
            })();
            IO_FAIL_AFTER.with(|fault| fault.set(None));
            if result.is_err() {
                injected += 1;
            }
            let marker = root.join(JOURNAL_DIR).join("commit").exists();
            drop(owner);
            let mut restarted = ManagedStore::open(&root).unwrap();
            restarted
                .recover()
                .unwrap_or_else(|error| panic!("boundary {boundary} did not recover: {error}"));
            let actual = std::fs::read(root.join(&groups_path)).unwrap();
            let expected_dump = if marker || committed || result.is_ok() {
                &new_dump
            } else {
                &old_dump
            };
            let actual_dump = std::fs::read(root.join(&dump_path)).unwrap();
            assert_eq!(
                actual_dump.as_slice(),
                expected_dump.as_slice(),
                "cache dump recovery at boundary {boundary}"
            );
            assert_eq!(
                crate::cache_dump::decode(&actual_dump).unwrap().len(),
                if marker || committed || result.is_ok() {
                    0
                } else {
                    1
                },
                "valid cache dump generation at boundary {boundary}"
            );
            if marker || committed || result.is_ok() {
                assert_eq!(actual, b"new", "committed boundary {boundary}");
            } else {
                assert_eq!(actual, b"old", "uncommitted boundary {boundary}");
            }
            drop(restarted);
            std::fs::remove_dir_all(root).unwrap();
            if result.is_ok() {
                break;
            }
        }
        assert!(
            injected >= 15,
            "filesystem matrix must exercise real write/rename/fsync/cleanup boundaries"
        );
    }

