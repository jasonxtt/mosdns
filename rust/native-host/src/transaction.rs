    #[cfg(unix)]
    #[test]
    fn sigkill_at_every_filesystem_boundary_recovers_whole_generation() {
        let _process_gate = PROCESS_PROBE_GATE.lock().unwrap();
        use std::os::unix::process::ExitStatusExt;
        let mut killed = 0;
        for boundary in 1..150 {
            let root = std::env::temp_dir().join(format!(
                "native-journal-kill-{}-{boundary}",
                std::process::id()
            ));
            let _ = std::fs::remove_dir_all(&root);
            std::fs::create_dir_all(root.join("webinfo")).unwrap();
            std::fs::write(root.join("webinfo/special_upstream_groups.json"), b"old").unwrap();
            let ready = root.join("ready");
            let mut child = std::process::Command::new(std::env::current_exe().unwrap())
                .args([
                    "--exact",
                    "transaction::tests::crash_writer_child",
                    "--ignored",
                    "--nocapture",
                ])
                .env("MOSDNS_TEST_CRASH_ROOT", &root)
                .env("MOSDNS_TEST_CRASH_AFTER", boundary.to_string())
                .stdout(std::process::Stdio::null())
                .stderr(std::process::Stdio::null())
                .spawn()
                .unwrap();
            let deadline = std::time::Instant::now() + std::time::Duration::from_secs(15);
            let finished = loop {
                if ready.exists() {
                    break None;
                }
                if let Some(status) = child.try_wait().unwrap() {
                    break Some(status);
                }
                if std::time::Instant::now() >= deadline {
                    child.kill().unwrap();
                    child.wait().unwrap();
                    panic!("crash child did not reach boundary {boundary}");
                }
                std::thread::sleep(std::time::Duration::from_millis(5));
            };
            if let Some(status) = finished {
                assert!(
                    status.success(),
                    "crash child exited before boundary {boundary}"
                );
                std::fs::remove_dir_all(root).unwrap();
                break;
            }
            let committed = std::fs::read(&ready).unwrap() == b"committed"
                || root.join(JOURNAL_DIR).join("commit").exists();
            assert!(
                std::process::Command::new("kill")
                    .args(["-KILL", &child.id().to_string()])
                    .status()
                    .unwrap()
                    .success()
            );
            assert_eq!(child.wait().unwrap().signal(), Some(9));
            killed += 1;
            let mut restarted = ManagedStore::open(&root).expect("SIGKILL releases writer lock");
            restarted
                .recover()
                .unwrap_or_else(|error| panic!("SIGKILL boundary {boundary}: {error}"));
            assert_eq!(
                std::fs::read(root.join("webinfo/special_upstream_groups.json")).unwrap(),
                if committed { b"new" } else { b"old" },
                "boundary {boundary}"
            );
            let generated = root.join("sub_config/special_groups.yaml");
            if committed {
                assert_eq!(std::fs::read(generated).unwrap(), b"new yaml");
            } else {
                assert!(
                    !generated.exists(),
                    "uncommitted new file at boundary {boundary}"
                );
            }
            restarted.recover().unwrap();
            drop(restarted);
            std::fs::remove_dir_all(root).unwrap();
        }
        assert!(
            killed >= 30,
            "must kill across preparation/replacement/marker/cleanup, got {killed}"
        );
        eprintln!("real SIGKILL/restart boundaries proved: {killed}");
    }

